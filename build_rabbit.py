#!/usr/bin/env python3
"""Put the rabbit from rabbit.json into index.html.

    python3 build_rabbit.py rabbit.json index.html

rabbit.json holds three poses ("leap", "gather", "stretch"), each a list of
layers {"kind": ..., "d": ...} in a 240 x 170 box, facing right. The poses
must share one structure (same layers, kinds, commands and number counts) so
the page can morph between them.

This writes:
  - the <symbol id="rabbit-sym"> (the leap pose) that every <use> points to;
  - const RABBIT = {...} between /* RABBIT:BEGIN */ and /* RABBIT:END */ for
    the canvases and the hopping rabbit.
Paths are rewritten in one canonical form ("M 1 2 C ..."), numbers rounded
to 2 decimals, so the page can split them on spaces.
"""
import json, re, sys

KINDS = {"back", "main", "line", "pink", "red", "white"}
ARGS = {"M": 2, "L": 2, "C": 6, "Q": 4, "A": 7, "Z": 0}
TOKEN = re.compile(r"[A-Za-z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def canon(d):
    """Parse a path (absolute M L C Q A Z only) into [(cmd, [numbers])]."""
    out, i, toks = [], 0, []
    # arc flags may be glued to each other or to the next number ("0110 20"); split them while tokenising
    pos, cmd, need = 0, None, 0
    s = d.strip()
    while pos < len(s):
        if s[pos] in " ,\t\n\r":
            pos += 1
            continue
        if s[pos].isalpha():
            c = s[pos]
            if c not in ARGS:
                raise ValueError(f"unsupported command {c!r} in {d[:60]}")
            toks.append(c); cmd = c; need = 0; pos += 1
            continue
        if cmd == "A" and need % 7 in (3, 4):
            toks.append(s[pos]); pos += 1; need += 1   # a flag is one character
            continue
        m = TOKEN.match(s, pos)
        if not m:
            raise ValueError(f"can't read {s[pos:pos+20]!r}")
        toks.append(m.group(0)); pos = m.end(); need += 1
    while i < len(toks):
        c = toks[i]; i += 1
        n = ARGS[c]
        if n == 0:
            out.append((c, []))
            continue
        first = True
        while first or (i < len(toks) and not toks[i].isalpha()):
            nums = [float(x) for x in toks[i:i + n]]
            if len(nums) != n:
                raise ValueError(f"{c} needs {n} numbers in {d[:60]}")
            out.append((c if first or c != "M" else "L", nums))
            i += n; first = False
    return out


def fmt(v):
    v = round(v, 2)
    return str(int(v)) if v == int(v) else f"{v:.2f}".rstrip("0")


def dstr(segs):
    return " ".join(c + "".join(" " + fmt(x) for x in nums) for c, nums in segs)


def main(src, page):
    poses = json.load(open(src, encoding="utf-8"))["poses"]
    names = ["leap", "gather", "stretch"]
    out = {}
    for name in names:
        layers = []
        for L in poses[name]:
            if L["kind"] not in KINDS:
                raise SystemExit(f"{name}: unknown kind {L['kind']}")
            layers.append({"k": L["kind"], "d": canon(L["d"])})
        out[name] = layers
    ref = out["leap"]
    for name in names[1:]:
        p = out[name]
        if [l["k"] for l in p] != [l["k"] for l in ref]:
            raise SystemExit(f"{name}: layer kinds differ from leap")
        for a, b in zip(ref, p):
            if [(c, len(n)) for c, n in a["d"]] != [(c, len(n)) for c, n in b["d"]]:
                raise SystemExit(f"{name}: a {a['k']} layer has a different command structure from leap")
            for (c, na), (_, nb) in zip(a["d"], b["d"]):
                if c == "A" and (na[3:5] != nb[3:5]):
                    raise SystemExit(f"{name}: arc flags differ from leap")

    paint = {
        "back": 'class="k-back" fill="#fff" stroke="#1D4EA6"',
        "main": 'class="k-main" fill="#fff" stroke="#1D4EA6"',
        "line": 'class="k-line" fill="none" stroke="#1D4EA6"',
        "pink": 'fill="#F6B4C3"',
        "red": 'fill="#E1252B"',
        "white": 'fill="#fff"',
    }
    sym = ('<symbol id="rabbit-sym" viewBox="0 0 240 170">\n      <g class="rb" stroke-linejoin="round" stroke-linecap="round">\n'
           + "".join(f'        <path {paint[l["k"]]} d="{dstr(l["d"])}"/>\n' for l in ref)
           + "      </g>\n    </symbol>")
    js = "const RABBIT = " + json.dumps({n: [{"k": l["k"], "d": dstr(l["d"])} for l in out[n]] for n in names}, ensure_ascii=False, separators=(",", ":")) + ";"

    html = open(page, encoding="utf-8").read()
    html, n1 = re.subn(r'<symbol id="rabbit-sym".*?</symbol>', lambda m: sym, html, count=1, flags=re.S)
    html, n2 = re.subn(r"/\* RABBIT:BEGIN[^*]*\*/.*?/\* RABBIT:END \*/", lambda m: "/* RABBIT:BEGIN · generated by build_rabbit.py from rabbit.json */\n" + js + "\n/* RABBIT:END */", html, count=1, flags=re.S)
    if n1 != 1 or n2 != 1:
        raise SystemExit(f"markers not found (symbol {n1}, RABBIT block {n2})")
    open(page, "w", encoding="utf-8").write(html)
    print(f"rabbit: {len(ref)} layers, symbol {len(sym)} chars, poses {len(js)} chars")


if __name__ == "__main__":
    main(*sys.argv[1:3])
